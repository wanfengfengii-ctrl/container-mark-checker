import { defineConfig } from "vitest/config";
import react from "@vitejs/plugin-react";

// In dev the frontend calls /api/* and Vite proxies it to the API.
// In production nginx performs the same proxy, so no CORS is needed.
export default defineConfig({
  plugins: [react()],
  server: {
    host: true,
    port: 5173,
    proxy: {
      "/api": {
        target: process.env.VITE_API_PROXY_TARGET ?? "http://localhost:8000",
        changeOrigin: true,
      },
    },
  },
  test: {
    environment: "jsdom",
    globals: true,
    setupFiles: ["./src/test/setup.ts"],
    exclude: ["e2e/**", "node_modules/**"],
  },
});
